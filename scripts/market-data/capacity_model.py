#!/usr/bin/env python3
"""Модель ёмкости рынка новостроек Удмуртии (агломерация Ижевска ≈ 95%).

Метрика: месяцы предложения по когортам сдачи + срок поглощения когорты-2028.
Пороги (зафиксированы в брифе ДО расчёта):
  зелёный  — навес когорты поглощён к сдаче +18 мес при БАЗОВОМ темпе
  жёлтый   — поглощён к сдаче +36 мес ИЛИ только в оптимистичном сценарии
  красный  — не поглощён к сдаче +36 мес даже в оптимистичном сценарии

Механика: помесячный шаг с 2026-08. Продажи месяца распределяются по когортам
пропорционально их непроданному остатку (упрощение, обсуждается в Ф4).
Новые запуски пополняют обобщённую когорту «пайплайн 2029+».

Все входы — из data/capacity/*.csv и данных ЕИСЖС репо; источники в комментариях.
"""

AVG_M2 = 49.5          # средняя площадь квартиры в текущей стройке УР (ЕИСЖС 11.07.2026)

# Непроданный остаток по когортам сдачи, квартир (ЕИСЖС срез 11.07.2026)
COHORTS = {
    '2026': 1414,
    '2027': 3336,
    '2028': 8613,
    '2029-30': 2264 + 387,
    'сданное': 223,     # готовый хвост (живой аудит 23.07.2026)
}
# месяц сдачи когорты (середина года сдачи — для дедлайнов светофора)
DELIVERY = {'2026': '2026-12', '2027': '2027-07', '2028': '2028-07', '2029-30': '2029-12'}

# Темпы продаж, квартир в ГОД (факт: поток = Δпроданного стока + продано в введённых,
# сверен с ипотекой первички; см. udm-stock-sales-monthly.csv и udm-mortgage-monthly.csv)
#   2024 ≈ 8 650 | 2025 ≈ 6 100 | 2026 (7 мес аннуализировано) ≈ 5 400
SCENARIOS = {
    # имя: {год: продажи_кв_год}; после последнего года — плоско
    'база':     {2026: 5400, 2027: 5700, 2028: 6000},          # ставка спадает медленно
    'оптимизм': {2026: 5400, 2027: 7000, 2028: 8500},          # возврат к темпу 2023-24
    'стресс':   {2026: 5400, 2027: 4000, 2028: 4000},          # семейную ипотеку урезали
}
# Новые запуски (пополнение пайплайна), квартир в год
LAUNCHES = {'база': 7500, 'оптимизм': 9000, 'стресс': 5000}
# факт для справки: 2024 — 6 559; 2025 — 10 532; 2026 за 6 мес — 3 755 (ДОМ.РФ 01_02_04)


def run(scenario):
    sales_plan = SCENARIOS[scenario]
    launches_y = LAUNCHES[scenario]
    stock = dict(COHORTS)
    stock['пайплайн'] = 0.0
    depleted = {}                      # когорта -> месяц обнуления
    y, m = 2026, 8
    for step in range(12 * 10):        # горизонт 10 лет
        sales_m = sales_plan.get(y, sales_plan[max(sales_plan)]) / 12
        stock['пайплайн'] += launches_y / 12
        total = sum(stock.values())
        if total <= 0:
            break
        for c in list(stock):
            take = sales_m * stock[c] / total
            stock[c] = max(0.0, stock[c] - take)
            if stock[c] < 1 and c not in depleted and c != 'пайплайн':
                depleted[c] = f'{y}-{m:02d}'
        m += 1
        if m > 12:
            m, y = 1, y + 1
    return depleted, stock


def months_between(a, b):
    ay, am = map(int, a.split('-')); by, bm = map(int, b.split('-'))
    return (by - ay) * 12 + (bm - am)


if __name__ == '__main__':
    print(f'Старт: непродано в стройке {sum(v for k, v in COHORTS.items() if k != "сданное"):.0f} кв'
          f' + сданное {COHORTS["сданное"]} кв')
    for sc in SCENARIOS:
        depleted, left = run(sc)
        print(f'\n=== Сценарий «{sc}» (продажи {SCENARIOS[sc]} кв/год, запуски {LAUNCHES[sc]}/год)')
        for c, dl in DELIVERY.items():
            end = depleted.get(c)
            if end:
                lag = months_between(dl, end)
                print(f'  когорта {c:8s}: распродана {end} (сдача {dl}, лаг {lag:+d} мес)')
            else:
                print(f'  когорта {c:8s}: НЕ распродана за горизонт 10 лет (остаток {left.get(c, 0):.0f})')
        # месяцы предложения на старте сценария
        y0 = SCENARIOS[sc][2026] / 12
        print(f'  месяцы предложения на 07.2026 (весь рынок): {sum(COHORTS.values()) / y0:.0f}')
